import { spawn } from 'node:child_process';
import { open, rm, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import { Paths, type Runner, atomicWrite, exists, optionalRead, selfInvocation } from '../system';
import { coreName } from '../platform';
import type { ServiceHost, ServiceState } from './types';

type RunState = { pid: number; image: string };
export type CoreLauncher = (paths: Paths) => Promise<number>;

async function readRun(paths: Paths): Promise<RunState | undefined> {
  const data = await optionalRead(paths.runState);
  if (!data) return;
  try {
    const value = JSON.parse(data.toString()) as { pid?: unknown; image?: unknown };
    if (typeof value.pid === 'number' && Number.isSafeInteger(value.pid) && value.pid > 0
        && typeof value.image === 'string' && value.image.length > 0) {
      return { pid: value.pid, image: value.image };
    }
  } catch { /* A truncated or stale state file means the core is not managed. */ }
  await rm(paths.runState, { force: true });
}

function quoteArgument(value: string): string {
  if (value.length > 0 && !/[\s"]/u.test(value)) return value;
  return `"${value.replaceAll('"', '\\"')}"`;
}

// The Startup folder cannot run a console program without flashing a window,
// so it starts wscript with this hidden launcher. Windows runs it at sign-in
// with the ordinary user token: no service account and no UAC prompt.
export function startupScript(): string {
  const command = [...selfInvocation(), '__run'].map(quoteArgument).join(' ');
  const literal = command.replaceAll('"', '""');
  return `' Generated by sbm. Starts sing-box in user mode at sign-in.\r\nSet shell = CreateObject("WScript.Shell")\r\nshell.Run "${literal}", 0, False\r\n`;
}

// Start the core detached with both logs inherited from private files. The
// CLI (or the hidden __run launcher) exits immediately; sing-box keeps running
// because Windows does not terminate a child when its parent exits.
export const spawnWindowsCore: CoreLauncher = async (paths) => {
  await paths.prepare();
  const stdout = await open(paths.stdout, 'a');
  const stderr = await open(paths.stderr, 'a');
  try {
    const child = spawn(paths.core, ['run', '-D', paths.base, '-c', paths.config], {
      cwd: paths.base, detached: true, windowsHide: true, stdio: ['ignore', stdout.fd, stderr.fd],
    });
    child.unref();
    if (!child.pid) throw new Error('Could not start sing-box.');
    return child.pid;
  } finally {
    await stdout.close();
    await stderr.close();
  }
};

export class WindowsUserHost implements ServiceHost {
  constructor(readonly paths: Paths, readonly runner: Runner, readonly launcher: CoreLauncher = spawnWindowsCore) {}

  async state(): Promise<ServiceState> {
    const run = await readRun(this.paths);
    if (!run) return { loaded: false, state: 'paused' };
    const result = await this.runner(['tasklist', '/FI', `PID eq ${run.pid}`, '/FO', 'CSV', '/NH']);
    if (result.code !== 0) throw new Error(`Cannot read process state: ${result.stderr.trim() || result.stdout.trim()}`);
    if (result.stdout.toLowerCase().includes(`"${run.image.toLowerCase()}"`)) {
      return { loaded: true, pid: run.pid, state: 'running' };
    }
    await rm(this.paths.runState, { force: true });
    return { loaded: false, state: 'paused' };
  }

  async start(): Promise<void> {
    if ((await this.state()).loaded) return;
    await this.paths.prepare();
    const pid = await this.launcher(this.paths);
    await atomicWrite(this.paths.runState, JSON.stringify({ pid, image: coreName('windows') }) + '\n');
  }

  async stop(): Promise<void> {
    // state() verifies the image name, so a recycled PID is never killed.
    const current = await this.state();
    if (!current.loaded || !current.pid) return;
    const result = await this.runner(['taskkill', '/PID', String(current.pid), '/T', '/F']);
    if (result.code !== 0 && result.code !== 128 && !/not found|no running instance/i.test(result.stderr)) {
      throw new Error(`taskkill failed (${result.code}): ${result.stderr.trim() || result.stdout.trim()}`);
    }
    await rm(this.paths.runState, { force: true });
  }

  async bootEnabled(): Promise<boolean> {
    return exists(this.paths.bootPlist);
  }

  async enableBoot(): Promise<void> {
    await mkdir(dirname(this.paths.bootPlist), { recursive: true });
    await atomicWrite(this.paths.bootPlist, startupScript(), 0o600);
  }

  async disableBoot(): Promise<void> {
    await rm(this.paths.bootPlist, { force: true });
  }
}
